// embed package (T5.10): Technical-Design §7, Product-Spec §2 (F-EXP-02, S).
//
// `exportEmbed` builds the project (`vite build`, live mode — `web` and
// `interactive` are free-time compositions that play themselves) and writes
// the embed package into the output dir: the unpacked site + the ES module
// `vanilla-scene.js` (`mountVanillaScene(el, { src, t })` + the
// `<vanilla-scene>` Web Component, the cross-framework interface) + the thin
// React wrapper `VanillaScene.tsx` + `embed-example.html` showing external-HTML
// usage. The scene loads in a shadow-DOM iframe, so host-page CSS cannot leak
// in and no framework is required on the host side.
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { throwIfCancelled, type WebJob } from './job';
import { type StepContext } from './run';
import { runViteBuild, type ViteBuildOptions } from './web';

/** Custom element name (the cross-framework interface). */
export const EMBED_ELEMENT = 'vanilla-scene';
/** ES module file (`mountVanillaScene` + element registration). */
export const EMBED_MODULE_FILE = 'vanilla-scene.js';
/** Thin React wrapper over the element. */
export const REACT_WRAPPER_FILE = 'VanillaScene.tsx';
/** External-HTML usage example. */
export const EMBED_EXAMPLE_FILE = 'embed-example.html';

/** ES module source for `vanilla-scene.js` (deterministic: no timestamps). */
export function buildEmbedModule(): string {
  return `// <vanilla-scene> embed runtime (generated by Vanilla Studio export).
//
// Loads an exported Vanilla Studio site ("./index.html" by default) inside a
// shadow-DOM iframe so the host page's CSS cannot leak in. Works from any
// static file server - no framework required:
//
//   <vanilla-scene src="./index.html" t="1.5"></vanilla-scene>
//   <script type="module" src="./vanilla-scene.js"></script>
//
// Programmatic use: mountVanillaScene(element, { src, t }) returns a cleanup
// function. "t" (seconds) becomes "?t=" for still-style scenes, which seek to
// it on load; free-time (web/interactive) scenes ignore it and just play.
const TAG = '${EMBED_ELEMENT}';
const DEFAULT_SRC = './index.html';

/** Resolve the iframe URL for the scene, anchored at the host document. */
function sceneUrl(doc, src, t) {
  const url = new URL(src, doc.baseURI);
  if (typeof t === 'number' && Number.isFinite(t) && t >= 0) url.searchParams.set('t', String(t));
  return url.toString();
}

/** Read mount options from element attributes ("src", "t"). */
function optionsFromElement(el) {
  const src = el.getAttribute('src') || DEFAULT_SRC;
  const rawT = el.getAttribute('t');
  const t = rawT === null || rawT === '' ? undefined : Number(rawT);
  return { src, t: typeof t === 'number' && Number.isFinite(t) && t >= 0 ? t : undefined };
}

/**
 * Mount a Vanilla Studio scene into any element.
 * Returns a cleanup function that removes the frame.
 */
export function mountVanillaScene(el, options) {
  const opts = options || {};
  const doc = el.ownerDocument;
  const shadow = el.shadowRoot || el.attachShadow({ mode: 'open' });
  const frame = doc.createElement('iframe');
  frame.setAttribute('title', 'vanilla scene');
  frame.setAttribute('loading', 'lazy');
  frame.setAttribute('src', sceneUrl(doc, opts.src || DEFAULT_SRC, opts.t));
  frame.style.cssText = 'border:0;width:100%;height:100%;display:block;';
  shadow.appendChild(frame);
  return function unmount() {
    frame.remove();
  };
}

/** <vanilla-scene src="./index.html" t="1.5"> - the cross-framework interface. */
export class VanillaSceneElement extends HTMLElement {
  static get observedAttributes() {
    return ['src', 't'];
  }

  connectedCallback() {
    this.mount();
  }

  disconnectedCallback() {
    this.unmount();
  }

  attributeChangedCallback() {
    if (this.isConnected) this.mount();
  }

  mount() {
    this.unmount();
    this._cleanup = mountVanillaScene(this, optionsFromElement(this));
  }

  unmount() {
    if (this._cleanup) {
      this._cleanup();
      this._cleanup = undefined;
    }
  }
}

if (typeof customElements !== 'undefined' && !customElements.get(TAG)) {
  customElements.define(TAG, VanillaSceneElement);
}
`;
}

/** TSX source for the thin React wrapper `VanillaScene.tsx`. */
export function buildReactWrapper(): string {
  return `// Thin React wrapper over <${EMBED_ELEMENT}> (generated by Vanilla Studio export).
//
// The Web Component is the cross-framework interface; this wrapper only maps
// props to attributes so React apps get types plus style/className support.
// The side-effect import registers the element (guarded, safe to import twice).
import { createElement, useEffect, useRef } from 'react';
import type { CSSProperties, ReactElement } from 'react';
import './${EMBED_MODULE_FILE}';

export interface VanillaSceneProps {
  /** Exported site entry (default "./index.html"). */
  src?: string;
  /** Scene time in seconds -> "?t=" (still-style scenes seek; free-time scenes ignore it). */
  t?: number;
  title?: string;
  className?: string;
  style?: CSSProperties;
}

/** Embed a Vanilla Studio scene: <VanillaScene src="./index.html" t={1.5} />. */
export function VanillaScene({ src, t, title = 'vanilla scene', className, style }: VanillaSceneProps): ReactElement {
  const ref = useRef<HTMLElement | null>(null);
  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (src === undefined) el.removeAttribute('src');
    else el.setAttribute('src', src);
    if (t === undefined) el.removeAttribute('t');
    else el.setAttribute('t', String(t));
  }, [src, t]);
  return createElement('${EMBED_ELEMENT}', { ref, title, className, style });
}
`;
}

/** Standalone HTML source for `embed-example.html`. */
export function buildEmbedExample(): string {
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>VanillaScene embed example</title>
    <style>
      body { margin: 2rem; font-family: system-ui, sans-serif; background: #141414; color: #eee; }
      ${EMBED_ELEMENT} { display: block; width: min(960px, 100%); aspect-ratio: 16 / 9; background: #000; }
    </style>
  </head>
  <body>
    <h1>VanillaScene embed</h1>
    <p>This page is outside the exported site. The scene below runs in a shadow-DOM iframe.</p>
    <${EMBED_ELEMENT} src="./index.html"></${EMBED_ELEMENT}>
    <script type="module" src="./${EMBED_MODULE_FILE}"></script>
  </body>
</html>
`;
}

export interface EmbedDeps {
  runBuild?: (options: ViteBuildOptions) => Promise<void>;
  copyDir?: (srcDir: string, destDir: string) => void;
}

/** Copy one directory level (avoids recursing into our own `.build` scratch dir). */
function copySiteInto(distDir: string, outDir: string, copyDir: (src: string, dest: string) => void): void {
  for (const entry of readdirSync(distDir)) {
    copyDir(path.join(distDir, entry), path.join(outDir, entry));
  }
}

/**
 * Build the project and write the embed package (unpacked site + module +
 * React wrapper + example). Emits progress; returns the entry file paths.
 */
export async function exportEmbed(job: WebJob, ctx: StepContext, deps: EmbedDeps = {}): Promise<string[]> {
  const runBuild = deps.runBuild ?? runViteBuild;
  const copyDir = deps.copyDir ?? ((src, dest) => cpSync(src, dest, { recursive: true }));
  const distDir = path.join(job.outDir, '.build', 'dist');
  throwIfCancelled(ctx.signal);
  ctx.onEvent({ type: 'progress', percent: 5, step: 'build', message: 'vite build' });
  mkdirSync(distDir, { recursive: true });
  await runBuild({
    projectDir: job.projectDir,
    distDir,
    ffmpeg: job.ffmpeg,
    signal: ctx.signal,
    onLog: (stream, line) => ctx.onEvent({ type: 'log', stream, line }),
  });
  throwIfCancelled(ctx.signal);
  if (!existsSync(path.join(distDir, 'index.html'))) throw new Error(`export worker: vite build produced no index.html in ${distDir}`);
  ctx.onEvent({ type: 'progress', percent: 70, step: 'embed', message: 'vanilla-scene.js + wrapper + example' });
  mkdirSync(job.outDir, { recursive: true });
  copySiteInto(distDir, job.outDir, copyDir);
  const moduleFile = path.join(job.outDir, EMBED_MODULE_FILE);
  const wrapperFile = path.join(job.outDir, REACT_WRAPPER_FILE);
  const exampleFile = path.join(job.outDir, EMBED_EXAMPLE_FILE);
  writeFileSync(moduleFile, buildEmbedModule());
  writeFileSync(wrapperFile, buildReactWrapper());
  writeFileSync(exampleFile, buildEmbedExample());
  rmSync(path.join(job.outDir, '.build'), { recursive: true, force: true });
  throwIfCancelled(ctx.signal);
  ctx.onEvent({ type: 'progress', percent: 100, step: 'done', message: 'embed package' });
  return [path.join(job.outDir, 'index.html'), moduleFile, wrapperFile, exampleFile];
}
