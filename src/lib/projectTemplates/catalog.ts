import { z } from 'zod';
import data from '../../../resources/project-templates/catalog.json';
import { BUILT_IN_PALETTES } from '@/lib/design/palettes';
import { applyPalette, readDesign, writeDesign } from '@/lib/design/workspaceDesign';
import { MEDIA_INTENTS } from '@/lib/guides/template';
import { emptyStoryboard } from '@/lib/storyboard/schema';
import { readStoryboard, writeStoryboard, writeStoryboardDoc } from '@/lib/storyboard/files';
import { readWorkspace } from '@/lib/workspace/file';
import { recordStudioChange } from '@/lib/workspace/workOrder';
import { STYLE_SCOPES } from '@/lib/styles/library';

// 프로젝트 템플릿(D-046): 신별 가이드 위에 놓이는 프로젝트 전체 뼈대(컨셉·서사·장면 슬롯).
// 앱은 뼈대 문서만 쓰고 신은 만들지 않는다. 슬롯을 신으로 옮기는 일은 에이전트 몫이다(D-022).

export const PROJECT_TEMPLATE_MD_REL = 'storyboard/00-project-template.md';

const localized = z.object({ ko: z.string().min(1), en: z.string().min(1) }).strict();

const slotSchema = z
  .object({
    id: z.string().min(1),
    role: z.string().min(1),
    sceneType: z.enum(['static', 'motion', '3d']),
    guide: z.string().regex(/^[a-z0-9][a-z0-9-]*@\d+$/),
    seconds: z.number().positive().optional(),
    purpose: z.string().min(1),
    visual: z.string().min(1),
    styles: z.array(z.object({ id: z.string().min(1), scope: z.enum(STYLE_SCOPES as ['scene', 'image', 'motion']) }).strict()),
  })
  .strict();

const templateSchema = z
  .object({
    id: z.string().regex(/^[a-z0-9][a-z0-9-]*$/),
    version: z.number().int().positive(),
    label: localized,
    summary: localized,
    mediaIntent: z.enum(MEDIA_INTENTS),
    paletteId: z.string().min(1),
    concept: z.string().min(1),
    narrativeArc: z.string().min(1),
    moodKeywords: z.array(z.string()),
    invariants: z.array(z.string()),
    variables: z.array(z.string()),
    slots: z.array(slotSchema).min(1),
  })
  .strict();

export type ProjectTemplate = z.infer<typeof templateSchema>;

const file = z.object({ version: z.literal(1), templates: z.array(templateSchema) }).strict().parse(data);

export const PROJECT_TEMPLATES: readonly ProjectTemplate[] = file.templates;

export const projectTemplateRef = (t: ProjectTemplate): string => `${t.id}@${t.version}`;

const bullets = (items: readonly string[]): string => items.map((i) => `- ${i}`).join('\n');

/** 에이전트가 읽는 뼈대 문서. 프롬프트류라 번역하지 않는다(AGENTS.md §3). */
export function renderProjectTemplateMd(t: ProjectTemplate): string {
  const slots = t.slots
    .map((s, i) =>
      [
        `### ${i + 1}. ${s.role} (\`${s.id}\`)`,
        '',
        `- type: ${s.sceneType}`,
        `- guide: \`${s.guide}\``,
        ...(s.seconds ? [`- seconds: ${s.seconds}`] : []),
        `- purpose: ${s.purpose}`,
        `- visual: ${s.visual}`,
        `- styles: ${s.styles.map((x) => `\`${x.id}\` (${x.scope})`).join(', ')}`,
      ].join('\n'),
    )
    .join('\n\n');
  return `${[
    `# Project template: ${t.label.en} (\`${projectTemplateRef(t)}\`)`,
    'Generated by Vanilla Studio. This is the skeleton for the whole project. The user brief overrides it: adapt, drop or add slots to fit, and record the result in `storyboard/02-design-flow.md`.',
    `## Concept\n\n${t.concept}`,
    `## Narrative arc\n\n${t.narrativeArc}`,
    `## Mood\n\n${t.moodKeywords.join(', ')}`,
    `## Invariants\n\n${bullets(t.invariants)}`,
    `## Variables\n\n${bullets(t.variables)}`,
    `## Palette\n\nSuggested: \`${t.paletteId}\`. Applying it is the user's choice; the tokens in \`DESIGN.md\` win.`,
    `## Scene slots\n\n${slots}`,
    [
      '## How to use it',
      '',
      '1. Write the storyboard documents from this skeleton and the brief.',
      '2. For each kept slot run `pnpm vanilla scaffold-scene <slug> --name "<name>" --type <type> --template <guide>`.',
      '3. Copy the slot styles into `scenes/<slug>/scene.json` as `styles: [{ "id": "...", "scope": "scene|image|motion" }]`, then run `pnpm vanilla sync-guides <slug>`.',
      '4. Look up other looks with `pnpm vanilla styles --query <word>` or in `STYLE_LIBRARY.json`.',
    ].join('\n'),
  ].join('\n\n')}\n`;
}

/** 뼈대 문서·storyboard 참조를 쓴다. 3대 문서와 신은 건드리지 않는다. */
export async function applyProjectTemplate(root: string, template: ProjectTemplate, opts: { palette: boolean }): Promise<void> {
  const ref = projectTemplateRef(template);
  const { file: current } = await readStoryboard(root);
  const ws = await readWorkspace(root);
  const base = current ?? emptyStoryboard(ws.workspaceId);
  await writeStoryboardDoc(root, PROJECT_TEMPLATE_MD_REL, renderProjectTemplateMd(template));
  await writeStoryboard(root, { ...base, visualDirection: { ...base.visualDirection, projectTemplate: ref } });
  const palette = opts.palette ? BUILT_IN_PALETTES.find((p) => p.id === template.paletteId) : undefined;
  if (palette) {
    const design = await readDesign(root);
    if (design !== null) await writeDesign(root, applyPalette(design, palette).text);
  }
  await recordStudioChange(root, {
    scope: 'workspace',
    targetId: ws.workspaceId,
    targetName: ws.name,
    summary: `프로젝트 템플릿 적용: ${ref} (${template.label.ko})`,
    fields: ['storyboard/00-project-template.md', ...(palette ? ['DESIGN.md'] : [])],
    layer: 'design-flow',
  }).catch(() => {});
}
